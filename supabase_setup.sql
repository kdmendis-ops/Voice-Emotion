-- Week 4 migration: pgvector embeddings and semantic retrieval

-- Enable the pgvector extension (safe to run multiple times)
CREATE EXTENSION IF NOT EXISTS vector;

-- Add 768-dimension embedding column (text-embedding-004 output size)
ALTER TABLE conversations ADD COLUMN IF NOT EXISTS embedding vector(768);

-- IVFFlat index for fast approximate cosine-similarity search
-- Run this after at least a handful of rows exist for best results
CREATE INDEX IF NOT EXISTS conversations_embedding_idx
  ON conversations
  USING ivfflat (embedding vector_cosine_ops)
  WITH (lists = 100);

-- RPC function used by search_similar() in supabase_client.py
-- Returns rows ordered by cosine distance (0.0 = identical, 2.0 = opposite)
CREATE OR REPLACE FUNCTION match_conversations(
  query_embedding   vector(768),
  match_session_id  text,
  match_count       int DEFAULT 5
)
RETURNS TABLE (
  id                uuid,
  session_id        text,
  user_input        text,
  transcript        text,
  emotion           text,
  casel_competency  text,
  gemini_response   text,
  sentiment         text,
  sentiment_score   float,
  keywords          text,
  created_at        timestamptz,
  cosine_distance   float
)
LANGUAGE sql STABLE AS $$
  SELECT
    id, session_id, user_input, transcript, emotion, casel_competency,
    gemini_response, sentiment, sentiment_score, keywords, created_at,
    (embedding <=> query_embedding) AS cosine_distance
  FROM conversations
  WHERE session_id = match_session_id
    AND embedding IS NOT NULL
  ORDER BY embedding <=> query_embedding
  LIMIT match_count;
$$;

