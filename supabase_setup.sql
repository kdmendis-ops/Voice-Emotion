-- Week 6 migration: safeguarding flag agent and teacher dashboard

-- Flag column on conversations so each entry records whether it triggered an alert
ALTER TABLE conversations ADD COLUMN IF NOT EXISTS flag_triggered BOOLEAN DEFAULT FALSE;

-- Safeguarding alerts table: one row per triggered flag event
CREATE TABLE IF NOT EXISTS safeguarding_alerts (
    id               UUID        DEFAULT gen_random_uuid() PRIMARY KEY,
    session_id       TEXT        NOT NULL,
    conversation_id  UUID        REFERENCES conversations(id) ON DELETE SET NULL,
    severity         TEXT        NOT NULL CHECK (severity IN ('low', 'medium', 'high')),
    reason           TEXT        NOT NULL,
    triggered_at     TIMESTAMPTZ DEFAULT NOW(),
    acknowledged_at  TIMESTAMPTZ,
    teacher_notes    TEXT
);

-- Fast lookup of unacknowledged alerts (teacher dashboard active-alerts view)
CREATE INDEX IF NOT EXISTS safeguarding_alerts_unacked_idx
    ON safeguarding_alerts (acknowledged_at)
    WHERE acknowledged_at IS NULL;

-- Per-session alert history ordered by most recent
CREATE INDEX IF NOT EXISTS safeguarding_alerts_session_idx
    ON safeguarding_alerts (session_id, triggered_at DESC);

-- Week 7 migration: weekly session summary reports generated by Summariser Agent

CREATE TABLE IF NOT EXISTS session_summaries (
    id           UUID        DEFAULT gen_random_uuid() PRIMARY KEY,
    session_id   TEXT        NOT NULL,
    period_start DATE        NOT NULL,
    period_end   DATE        NOT NULL,
    summary_text TEXT        NOT NULL,   -- full Gemini JSON response
    created_at   TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS session_summaries_session_idx
    ON session_summaries (session_id, created_at DESC);
